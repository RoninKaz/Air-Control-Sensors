MAX_KM = 650  # центр района не может быть дальше этого от центра своей области


def km(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))


def find(names, capital):
    """Лучший кандидат в Казахстане, ближайший к центру области."""
    best = None
    for name in names:
        for lang in ("ru", "en"):
            try:
                r = requests.get(GEO_URL, params={"name": name, "count": 20, "language": lang,
                                                  "countryCode": "KZ", "format": "json"}, timeout=15)
                results = r.json().get("results") or []
            except Exception:  # noqa: BLE001
                results = []
            for x in results:
                p = (round(x["latitude"], 3), round(x["longitude"], 3))
                d = km(p, capital)
                if d <= MAX_KM and (best is None or d < best[1]):
                    best = (p, d, name)
            time.sleep(0.15)
            if best:
                return best
    return best


def main():
    out, missing = {}, []
    total = sum(len(v[1]) for v in DATA.values())
    n = 0
    for region, (capital, districts) in DATA.items():
        out[region] = {}
        for district, names in districts:
            n += 1
            hit = find(names, capital)
            if hit:
                out[region][district] = hit[0]
                print(f"[{n}/{total}] OK   {region} / {district}: {hit[2]} {hit[0]} ({hit[1]:.0f} км от центра области)")
            else:
                missing.append(f"{region} / {district} ({', '.join(names)})")
                print(f"[{n}/{total}] НЕТ  {region} / {district}")
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "backend", "regions.py")
    with open(path, "w", encoding="utf-8") as f:
        f.write('"""Районы областей Казахстана: {область: {район: (широта, долгота центра района)}}.\n'
                'Файл создан скриптом tools/build_regions.py (геокодер Open-Meteo)."""\n\nREGIONS = {\n')
        for region, ds in out.items():
            f.write(f"    {region!r}: {{\n")
            for d, (la, lo) in ds.items():
                f.write(f"        {d!r}: ({la}, {lo}),\n")
            f.write("    },\n")
        f.write("}\n")
    print(f"\nГотово: {sum(len(v) for v in out.values())} из {total} районов записаны в backend/regions.py")
    if missing:
        print("Не найдены:\n  " + "\n  ".join(missing))


if __name__ == "__main__":
    main()
