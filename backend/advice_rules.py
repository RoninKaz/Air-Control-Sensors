"""
Советы по правилам — команда БЭКЕНДА.

Работают всегда, даже без ИИ. Если ИИ не ответил — приложение
показывает эти советы.

ДОГОВОРЁННОСТЬ:
  get_rule_advice(air) -> словарь advice
      {"adults": "...", "children": "...", "asthma": "...",
       "sport": "...", "airing": "..."}
"""

# (верхняя граница AQI, взрослые, дети, астма и аллергия, спорт)
RULES = [
    (50,
     "Можно гулять и заниматься делами на улице.",
     "Можно гулять и играть на улице.",
     "Воздух чистый, можно выходить.",
     "Отличное время для тренировки на улице."),
    (100,
     "Можно гулять как обычно.",
     "Гулять можно, но без долгих активных игр.",
     "Сократите время на улице, держите лекарства под рукой.",
     "Лёгкая тренировка на улице, интенсивную лучше в зале."),
    (150,
     "Выходите ненадолго, долгие прогулки лучше отложить.",
     "Гулять не дольше 30–60 минут.",
     "Лучше остаться дома.",
     "Тренируйтесь в зале."),
    (200,
     "Сократите время на улице.",
     "Лучше остаться дома.",
     "Оставайтесь дома, закройте окна.",
     "Тренируйтесь в зале или отдохните."),
    (10_000,
     "Без необходимости не выходите, на улице — маска.",
     "Оставайтесь дома.",
     "Оставайтесь дома, закройте окна.",
     "Сегодня без тренировок на улице."),
]


def _airing(air):
    aqi = air.get("aqi", 0)
    t = air.get("t")
    if aqi > 150:
        return "Проветривать не стоит: на улице грязный воздух. Откройте окно позже."
    if aqi > 100:
        return "Проветривайте коротко, 3–5 минут, и закройте окна."
    if t is not None and t < -10:
        return "На улице сильный мороз: проветривайте коротко, 3–5 минут."
    if t is not None and t > 30:
        return "На улице жарко: проветривайте утром или вечером."
    return "Хорошее время проветрить комнату 10–15 минут."


def get_rule_advice(air):
    aqi = air.get("aqi", 0)
    for top, adults, children, asthma, sport in RULES:
        if aqi <= top:
            break
    return {
        "adults": adults,
        "children": children,
        "asthma": asthma,
        "sport": sport,
        "airing": _airing(air),
    }
